#!/usr/bin/env python3
"""Weekly backup of the data that cannot be fetched again.

Supabase's free plan has no backups. Most of the database can be rebuilt (the
history import re-reads the public dataset; signals and backtests can be
recomputed), but some cannot: prices captured from NEPSE each day, floorsheet
summaries (NEPSE only publishes the current day's floorsheet), the published
calls and price ranges, the adjustment decisions and the run log.

This writes those tables as gzipped JSON lines plus a manifest into a folder,
which the workflow keeps as a downloadable artifact for 90 days. Restore with
scripts/analytics/restore_backup.py (see docs/phase5-quality.md).
"""

from __future__ import annotations

import gzip
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "ingest"))
from common import JobError, Supabase, write_summary  # noqa: E402

# Restore order: referenced tables first. (table, sort key, restore key, filters)
# The restore key is the unique key rows are matched on when restoring. Tables whose
# id is generated by the database are matched on their natural unique key instead,
# and their id is left for the database to assign. The run log has no natural key:
# it is kept for reference and not restored.
TABLES: list[tuple[str, str, str | None, dict[str, str]]] = [
    ("sectors", "id", "id", {}),
    ("indices", "id", "id", {}),
    ("companies", "id", "id", {}),
    ("price_adjustments", "company_id,ex_date", "company_id,ex_date", {}),
    ("corporate_actions", "id", "company_id,action_type,fiscal_year,book_close_date", {}),
    ("fundamentals", "company_id,fiscal_year,quarter", "company_id,fiscal_year,quarter", {}),
    ("market_daily", "date", "date", {}),
    ("index_daily", "index_id,date", "index_id,date", {}),
    # Rows from NEPSE and Sharesansar. Rows from the public CSV dataset come back with the history import.
    ("daily_prices", "company_id,date", "company_id,date", {"source": "neq.csv"}),
    ("floorsheet_daily", "company_id,date", "company_id,date", {}),
    ("signals", "company_id,date", "company_id,date", {}),
    ("forecasts", "company_id,made_on,horizon,model", "company_id,made_on,horizon,model", {}),
    ("quality_issues", "id", "trade_date,company_id,check_name", {}),
    ("issues", "id", "company_name,issue_type,audience,open_date", {}),
    ("job_runs", "id", None, {}),
]


def backup(db: Supabase, out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    manifest = {"created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "tables": []}
    for table, key, restore_key, filters in TABLES:
        rows = db.select_all(table, select="*", order=",".join(f"{k}.asc" for k in key.split(",")), **filters)
        path = out / f"{table}.jsonl.gz"
        with gzip.open(path, "wt", encoding="utf-8") as handle:
            for row in rows:
                handle.write(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n")
        manifest["tables"].append({"table": table, "key": restore_key, "filters": filters, "rows": len(rows),
                                   "file": path.name, "bytes": path.stat().st_size})
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def main() -> None:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "backup")
    manifest = backup(Supabase(), out)
    total = sum(t["bytes"] for t in manifest["tables"])
    lines = [f"## Backup {manifest['created_at']}", "", "| Table | Rows | Size |", "|---|---:|---:|"]
    lines += [f"| {t['table']} | {t['rows']:,} | {t['bytes'] / 1024:,.0f} KB |" for t in manifest["tables"]]
    lines += ["", f"Total {total / 1024 / 1024:.1f} MB, kept as this run's artifact for 90 days."]
    write_summary("\n".join(lines))
    if not any(t["table"] == "daily_prices" and t["rows"] > 0 for t in manifest["tables"]):
        raise JobError("the backup has no daily prices: something is wrong with the database or the export")


if __name__ == "__main__":
    try:
        main()
    except JobError as exc:
        write_summary(f"## Backup failed\n\n{exc}")
        sys.exit(1)
