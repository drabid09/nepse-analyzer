-- Phase 1, migration 1: core tables and indexes.
--
-- Conventions
--   * Dates are AD (Gregorian). Bikram Sambat is a display concern, done in the website.
--   * Money is NPR, numeric(.., 2). Ratios and indicators are `real`: they are
--     derived values, and 4 bytes per value keeps us inside Supabase's 500 MB.
--   * Text columns with a CHECK list are used instead of enum types so a new
--     value is a one-line migration.
--   * Every time-series table has its "one entity over time" key as the primary
--     key (company_id, date). A second index on the date alone serves the
--     "whole market on one day" queries (dashboard, screener, heat map).

-- ---------------------------------------------------------------- reference data

create table public.sectors (
  id    smallint generated by default as identity primary key,
  name  text not null unique,  -- exactly as NEPSE's company list spells it
  slug  text not null unique   -- URL-safe key, e.g. 'commercial-banks'
);

create table public.indices (
  id         smallint primary key,  -- NEPSE's own index id (58 = NEPSE Index)
  code       text not null unique,  -- stable key for URLs, e.g. 'nepse', 'banking'
  name       text not null,
  kind       text not null check (kind in ('main', 'sector')),
  sector_id  smallint references public.sectors (id)
);

create table public.companies (
  id                 integer generated by default as identity primary key,
  symbol             text not null unique,
  name               text not null,
  sector_id          smallint references public.sectors (id),
  -- As NEPSE reports it ('Equity', ...). Null when the security is tradable but
  -- absent from NEPSE's company list, which is how promoter shares appear.
  instrument_type    text,
  status             text,                           -- NEPSE status code, 'A' = active
  is_tradable        boolean not null default false, -- in NEPSE's active security list
  -- NEPSE uses separate ids for the company and for its tradable security.
  -- History and detail calls need the security id.
  nepse_company_id   integer,
  nepse_security_id  integer unique,
  regulator          text,
  website            text,
  isin               text,
  listing_date       date,
  face_value         numeric(10, 2),
  listed_shares      bigint,
  paid_up_capital    numeric(18, 2),
  market_cap         numeric(20, 2),
  promoter_pct       real,
  public_pct         real,
  updated_at         timestamptz not null default now()
);

create index companies_sector_idx on public.companies (sector_id);

-- ---------------------------------------------------------------- prices

-- One row per company per trading day. During the session the live job keeps
-- today's row up to date (is_final = false, close = last traded price); the
-- end-of-day job then marks it final. So "latest quote" is simply today's row.
create table public.daily_prices (
  company_id  integer not null references public.companies (id) on delete cascade,
  date        date not null,
  open        numeric(12, 2),  -- nullable: NEPSE's own history has no opening price
  high        numeric(12, 2),
  low         numeric(12, 2),
  close       numeric(12, 2) not null,
  prev_close  numeric(12, 2),
  volume      bigint,
  turnover    numeric(18, 2),
  trades      integer,
  -- Prices are stored as traded. Multiply by adj_factor to get the price
  -- adjusted for later bonus, right and cash-dividend events (1 = no adjustment).
  adj_factor  real not null default 1,
  is_final    boolean not null default true,
  source      text not null,   -- 'nepse', 'csv' (history backfill) or 'sharesansar'
  primary key (company_id, date)
);

create index daily_prices_date_idx on public.daily_prices (date);

-- Intraday points, about every 5 minutes. Kept only for recent weeks; the
-- ingestion job aggregates and deletes older rows.
create table public.intraday_snapshots (
  company_id  integer not null references public.companies (id) on delete cascade,
  ts          timestamptz not null,
  ltp         numeric(12, 2) not null,
  volume      bigint,          -- cumulative for the day at ts
  primary key (company_id, ts)
);

create index intraday_snapshots_ts_idx on public.intraday_snapshots (ts);

-- ---------------------------------------------------------------- indices and market

create table public.index_daily (
  index_id    smallint not null references public.indices (id) on delete cascade,
  date        date not null,
  open        numeric(12, 2),
  high        numeric(12, 2),
  low         numeric(12, 2),
  close       numeric(12, 2) not null,
  prev_close  numeric(12, 2),
  turnover    numeric(18, 2),
  is_final    boolean not null default true,
  primary key (index_id, date)
);

create index index_daily_date_idx on public.index_daily (date);

create table public.index_intraday (
  index_id  smallint not null references public.indices (id) on delete cascade,
  ts        timestamptz not null,
  value     numeric(12, 2) not null,
  primary key (index_id, ts)
);

create index index_intraday_ts_idx on public.index_intraday (ts);

-- Whole-market totals for one trading day.
create table public.market_daily (
  date              date primary key,
  turnover          numeric(18, 2),
  traded_shares     bigint,
  transactions      integer,
  scrips_traded     integer,
  market_cap        numeric(20, 2),
  float_market_cap  numeric(20, 2),
  advancers         integer,
  decliners         integer,
  unchanged         integer,
  is_final          boolean not null default true
);

-- One summary row per company per day, computed from the day's floorsheet.
-- The raw floorsheet (about 40,000 trades a day) is never stored.
create table public.floorsheet_daily (
  company_id          integer not null references public.companies (id) on delete cascade,
  date                date not null,
  trades              integer not null,
  quantity            bigint not null,
  amount              numeric(18, 2) not null,
  vwap                numeric(12, 2),
  largest_trade_qty   bigint,
  buyer_brokers       smallint,  -- distinct brokers on the buy side
  seller_brokers      smallint,
  top_buyers          jsonb,     -- [{"broker": 45, "qty": 1200, "amount": 675600.0}, ...] top 5
  top_sellers         jsonb,
  primary key (company_id, date)
);

create index floorsheet_daily_date_idx on public.floorsheet_daily (date);

-- ---------------------------------------------------------------- corporate events

-- Bonus, cash dividend, right share and similar events. A combined
-- "10% bonus + 5% cash" announcement is stored as two rows.
create table public.corporate_actions (
  id               bigint generated always as identity primary key,
  company_id       integer not null references public.companies (id) on delete cascade,
  action_type      text not null check (action_type in ('bonus', 'cash_dividend', 'right', 'split', 'merger', 'other')),
  fiscal_year      text,            -- BS fiscal year as published, e.g. '2082/83'
  announced_on     date,
  book_close_date  date,
  bonus_pct        numeric(8, 4),
  cash_pct         numeric(8, 4),
  right_ratio      text,            -- as announced, e.g. '1:0.5'
  right_pct        numeric(8, 4),   -- right shares offered per 100 held
  right_price      numeric(12, 2),
  adj_factor       real,            -- factor applied to earlier prices; set by the adjuster
  source           text not null,
  source_url       text,
  note             text,
  created_at       timestamptz not null default now(),
  -- Re-running a fetch must not duplicate an event, even when some parts are unknown.
  constraint corporate_actions_event_key
    unique nulls not distinct (company_id, action_type, fiscal_year, book_close_date)
);

create index corporate_actions_book_close_idx on public.corporate_actions (book_close_date);

-- IPO, FPO, right-share and similar public issues, upcoming and past.
create table public.issues (
  id              bigint generated always as identity primary key,
  company_id      integer references public.companies (id) on delete set null,  -- null until listed
  symbol          text,
  company_name    text not null,
  issue_type      text not null check (issue_type in ('ipo', 'fpo', 'right', 'debenture', 'mutual_fund', 'other')),
  audience        text,            -- as published: general public, locals, foreign employment, ...
  sector_id       smallint references public.sectors (id),
  units           bigint,
  price           numeric(12, 2),
  ratio           text,            -- right-share ratio as announced
  open_date       date,
  close_date      date,
  allotment_date  date,
  listing_date    date,
  status          text not null default 'upcoming'
                  check (status in ('upcoming', 'open', 'closed', 'allotted', 'listed', 'cancelled')),
  issue_manager   text,
  rating          text,
  listing_open    numeric(12, 2),  -- first trading day, for "how did similar issues list?"
  listing_close   numeric(12, 2),
  source          text not null,
  source_url      text,
  updated_at      timestamptz not null default now(),
  constraint issues_issue_key
    unique nulls not distinct (company_name, issue_type, audience, open_date)
);

create index issues_status_open_idx on public.issues (status, open_date);

-- Reported financials. quarter 4 holds the full-year figures.
create table public.fundamentals (
  company_id       integer not null references public.companies (id) on delete cascade,
  fiscal_year      text not null,     -- BS fiscal year, e.g. '2082/83'
  quarter          smallint not null check (quarter between 1 and 4),
  period_end       date,
  reported_on      date,
  eps              numeric(12, 2),    -- as reported by the company
  book_value       numeric(12, 2),    -- net worth per share
  net_profit       numeric(18, 2),
  paid_up_capital  numeric(18, 2),
  reserves         numeric(18, 2),
  roe              real,
  roa              real,
  npl_pct          real,              -- banks and finance companies only
  extra            jsonb,             -- sector-specific figures that have no column
  source           text not null,
  updated_at       timestamptz not null default now(),
  primary key (company_id, fiscal_year, quarter)
);

-- ---------------------------------------------------------------- analytics output

-- One row per company per day from the analytics job. History is kept so each
-- signal's later outcome can be measured and shown as its track record.
create table public.signals (
  company_id           integer not null references public.companies (id) on delete cascade,
  date                 date not null,
  recommendation       text not null check (recommendation in ('buy', 'hold', 'sell', 'avoid')),
  score                smallint not null check (score between 0 and 100),
  confidence           text not null check (confidence in ('low', 'medium', 'high')),
  trend_short          text check (trend_short in ('up', 'sideways', 'down')),
  trend_medium         text check (trend_medium in ('up', 'sideways', 'down')),
  trend_long           text check (trend_long in ('up', 'sideways', 'down')),
  buy_low              numeric(12, 2),
  buy_high             numeric(12, 2),
  take_profit_low      numeric(12, 2),
  take_profit_high     numeric(12, 2),
  stop_loss            numeric(12, 2),
  support              numeric(12, 2),
  resistance           numeric(12, 2),
  -- Snapshot of the numbers the screener filters on.
  rsi_14               real,
  macd_hist            real,
  volatility_30d       real,
  volume_ratio         real,   -- today's volume / 20-day average
  rel_strength_sector  real,
  rel_strength_index   real,
  pe                   real,
  pb                   real,
  eps                  real,
  dividend_yield       real,
  reasons_for          jsonb not null default '[]',
  reasons_against      jsonb not null default '[]',
  primary key (company_id, date)
);

create index signals_date_idx on public.signals (date, recommendation, score desc);

-- Price-range estimates. Always a range (low..high) with a middle value, never
-- a single promised price. actual_close is filled in once target_date passes.
create table public.forecasts (
  company_id    integer not null references public.companies (id) on delete cascade,
  made_on       date not null,
  horizon       text not null check (horizon in ('1W', '1M', '3M')),
  model         text not null,     -- 'trend', 'arima', 'mean_reversion', 'ensemble', ...
  target_date   date not null,
  base_close    numeric(12, 2) not null,
  low           numeric(12, 2) not null,
  mid           numeric(12, 2) not null,
  high          numeric(12, 2) not null,
  band_pct      smallint not null default 80 check (band_pct between 1 and 99),
  reliable      boolean not null default true,
  note          text,
  actual_close  numeric(12, 2),
  primary key (company_id, made_on, horizon, model),
  check (low <= mid and mid <= high)
);

create index forecasts_unscored_idx on public.forecasts (target_date) where actual_close is null;

-- Measured performance of a trading strategy or a forecast model.
create table public.backtest_results (
  id                 bigint generated always as identity primary key,
  company_id         integer references public.companies (id) on delete cascade,  -- null = whole market
  kind               text not null check (kind in ('strategy', 'forecast')),
  name               text not null,              -- strategy or model name
  variant            text not null default '',   -- horizon or parameter label
  params             jsonb not null default '{}',
  period_start       date not null,
  period_end         date not null,
  sample_size        integer not null,           -- trades or forecasts evaluated
  hit_rate           real,
  avg_gain_pct       real,
  avg_loss_pct       real,
  total_return_pct   real,
  max_drawdown_pct   real,
  mae_pct            real,                       -- forecasts: mean absolute error
  band_coverage_pct  real,                       -- forecasts: how often the range held
  reliable           boolean not null,
  note               text,
  trades             jsonb,                      -- compact trade list for the chart
  computed_at        timestamptz not null default now(),
  constraint backtest_results_key
    unique nulls not distinct (company_id, kind, name, variant)
);
